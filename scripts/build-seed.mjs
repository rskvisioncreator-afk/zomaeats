const slug = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')

const seedRestaurants = restaurants.map(({ menu, ...r }) => ({
  ...r,
  dishCount: menu.length,
}))

const seedDishes = restaurants.flatMap((r) =>
  r.menu.map(([name, price, category, isVeg, image, isBestseller, description]) => ({
    id: `${r.id}-${slug(name)}`,
    restaurantId: r.id,
    name,
    description: description || descriptions[category] || descriptions['North Indian'],
    price,
    image: img(image),
    category,
    isVeg,
    isBestseller,
    serves: isVeg && price < 150 ? 1 : 2,
    rating: Math.min(4.9, Number((r.rating + (isBestseller ? 0.1 : -0.1)).toFixed(1))),
  })),
)

const out = { restaurants: seedRestaurants, dishes: seedDishes }
writeFileSync(join(__dirname, '..', 'src', 'data', 'seed.json'), JSON.stringify(out, null, 2))
console.log(`seed.json written: ${seedRestaurants.length} restaurants, ${seedDishes.length} dishes`)
